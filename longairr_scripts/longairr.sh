# Show main help message
show_help() {
    echo ""
    echo "LongAIRR version: ${LONGAIRR_VERSION}"
    echo ""
    echo "Usage: longairr [COMMAND] [OPTIONS]"
    echo ""
    echo "Description: "
    echo ""
    echo "Commands:"
    echo "  basecall       |  Perform ONT basecalling and generate a quality report"
    echo "  filter         |  [OPTIONAL] Perform Quality / length filtering and generate a quality report"
    echo "  demux          |  [OPTIONAL|BULK] Perform Sample demultiplexing on bulk samples"
    echo "  collapse       |  Perform annotation of UMI / Spatial barcode sequences, collapse sequences on specified GROUP field by running MSA and Consensus building"
    echo "  seqtag         |  [OPTIONAL] Perform annotation of the constant region or other provided anchor sequences"
    echo "  airr           |  Assign V(D)J genes + conversion to AIRR-conform output"
    echo "  report         |  Creates a run-summary and HTML-report summarizing run information."
    echo "  -h, --help     |  Show this help message and exit"
    echo "  -v, --version  |  Show version information and exit"
}

show_version() {
    echo "LongAIRR version ${LONGAIRR_VERSION}"
}

# Execute longairr functions
case "$1" in
  basecall|bc)
    shift
    basecall "$@"
    ;;
  filter)
    shift
    filter "$@"
    ;;
  demux)
    shift
    demux "$@"
    ;;
  collapse)
    shift
    collapse "$@"
    ;;
  seqtag)
    shift
    seqtag "$@"
    ;;
  airr)
    shift
    airr "$@"
    ;;
  report)
    shift
    report "$@"
    ;;
  -h|--help)
    show_help
    exit 0
    ;;
  -v|--version)
    show_version
    exit 0
    ;;
  *)
    printf "Error: Unknown command. Choose valid subcommand. \n"
    show_help
    exit 1
    ;;
esac
