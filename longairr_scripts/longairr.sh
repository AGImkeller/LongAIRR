################################################################################
# LongAIRR seqtag function
#
# Description:
#   Annotates reads with specified anchor. Option to split files by regex contained in the anchor-IDs.
#   Possible use-case is isotype/constant region annotation or matching reads to ig/tcr specific anchors and 
#   split them in loci-specific files.
#
# Arguments:
#   --window-length <VALUE>         Window length for anchor-match search (default: 220)
#   --anchor-error  <VALUE>         Maximum allowed mismatches for anchor match (default: 0.1)
#   --pf            <VALUE>         Slot identifier name in FASTA header (default: ISOTYPE)
#   --split         <TRUE|FALSE>    Whether to split annotated reads by a specific slot in the FASTA header (default: FALSE)
#   --split-regex   <VALUE1,VALUE2> Comma-separated values used to split (and combine) when --split is set to TRUE
#   --run-root <PATH>               Explicit LongAIRR run root (default: auto-detect from output)
#   --sample <VALUE>                Optional sample identifier for sample-level metadata
#   --verbose       <TRUE|FALSE>    Whether to print detailed runtime information (default: TRUE)
#   -h, --help                      Show this help message and exit
#
# Input:
#   input_anchor | Path to FASTA file containing isotype/constant region sequences
#   input_seqs          | Path to FASTA file containing UMI-annotated sequences
#   outdir             | Path to the output directory
#
# Output:
#   Files are saved in 'output/seqtag/'
#
#   The function generates multiple outputs:
#     - Annotated FASTA file with constant region assignments
#     - Optionally split FASTA files if --split is enabled
#
################################################################################
seqtag() {

  # parameters
  local input_anchor
  local input_seqs
  local output

  local requested_run_root=""
  local metadata_sample=""

  local window_length=220
  local max_error=0.1
  local primer_field="ISOTYPE"

  local split="FALSE"
  local split_regex=("Ig" "TCR") # Regex specifying which files are combined after splitting according to --pf
    
  local verbose="TRUE"
  # progress bar
  local current_step=0
  local constant_steps=2
  
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --window-length)
        window_length=$2
        shift 2
        ;;
      --anchor-error)
        max_error=$2
        shift 2
        ;;
      --pf)
        primer_field="$2"
        shift 2
        ;;
      --split)
        split=$(echo "$2" | tr '[:lower:]' '[:upper:]')
        # NOTE: Internal function [see longairr_utils.sh]
        validate_boolean_parameters '--split' "${split}"
        shift 2
        ;;
      --split-regex)
        if [ -n "$2" ]; then
          IFS=',' read -ra split_regex <<< "$2"
          shift 2
        else
          echo "--split-regex option requires an argument." >&2
          exit 1
        fi
        ;;
      --run-root)
        requested_run_root="$2"
        shift 2
        ;;
      --sample)
        metadata_sample="$2"
        shift 2
        ;;
      --verbose)
        verbose=$(echo "$2" | tr '[:lower:]' '[:upper:]')
        validate_boolean_parameters '--verbose' "${verbose}"
        shift 2
        ;;
      -h|--help)
        show_help_seqtag
        exit 0
        ;;
      *)
        if [[ -z "${input_anchor}" ]]; then
          input_anchor="$1"
        elif [[ -z "${input_seqs}" ]]; then
          input_seqs="$1"
        elif [[ -z "${output}" ]]; then
          output="$1"
        else
          echo "Unexpected argument \"$1\". For detailed usage, run 'longairr seqtag --help'."
          exit 1
        fi
        shift
        ;;
    esac
  done

  if [[ -z "${input_seqs}" || -z "${input_anchor}" || -z "${output}" ]]; then
    echo "ERROR: Missing required arguments: all input and output parameters must be specified."
    echo "For detailed usage, run 'longairr seqtag --help'."
    exit 1
  fi

  if [[ ! -d "${output}" ]]; then
    echo "ERROR: Specified output path \"${output}\" is not a valid directory."
    echo "Ensure the path exists and is writable."
    exit 1
  fi

  #-----LOG FILE and PROGRESS BAR-----#

  local log_path="${output%/}/seqtag/"
  mkdir -p "${log_path}"
  local log_file="${log_path}longairr_seqtag.log"

  echo -e "\n###################\n#longairr seqtag#\n###################\n" | tee -a "${log_file}"

  if [[ "${split}" == "TRUE" ]]; then
    constant_steps=4
  else
    constant_steps=2
  fi
  # NOTE: Internal function (see longairr_utils.sh)
  progress_bar ${current_step} ${constant_steps}

  #-----INPUT CHECKS-----#

  if [[ ! -f "${input_seqs}" ]]; then
    log_message "ERROR" "longairr seqtag" \
      "Specified input sequence file does not exist. For detailed usage, run 'longairr seqtag --help'." \
      "${log_file}"
    exit 1
  elif [[ "${input_seqs}" != *.fasta ]]; then
    log_message "ERROR" "longairr seqtag" \
      "Input file \"${input_seqs}\" must have a valid FASTA extension (.fasta)." \
      "${log_file}"
    exit 1
  fi

  if [[ ! -f "${input_anchor}" ]]; then
    log_message "ERROR" "longairr seqtag" \
      "Specified input annotation file does not exist. For detailed usage, run 'longairr seqtag --help'." \
      "${log_file}"
    exit 1
  elif [[ "${input_anchor}" != *.fasta ]]; then
    log_message "ERROR" "longairr seqtag" \
      "Input file \"${input_anchor}\" must have a valid FASTA extension (.fasta)." \
      "${log_file}"
    exit 1
  fi

  # Set up seqtag output- and intermediate directories
  local seqtag_out="${output%/}/seqtag/"
  local seqtag_tmp="${seqtag_out}tmp/"
  mkdir -p "${seqtag_tmp}"
  
  #--------FUNCTIONALITY-------#
  
  local metadata_started_at
  metadata_started_at=$(date -Iseconds)

  # Define file paths
  #local split_in="${seqtag_out}/longairr_seqtag_primers-pass.fasta"
  local matched_fasta="${seqtag_out}longairr_seqtag_primers-pass.fasta"
  local failed_fasta="${seqtag_out}longairr_seqtag_primers-fail.fasta"
  
  # Matches annotation anchors and writes match into sequence header
  # NOTE: Find the reference for third-party software 'presto [MaskPrimers.py]' in '/vignette/software_references.md`
  MaskPrimers.py align --failed -s "${input_seqs}" --skiprc -p "${input_anchor}" --maxlen ${window_length} --maxerror ${max_error} --mode tag --revpr --pf "${primer_field}" --outname longairr_seqtag --outdir "${seqtag_out}" >> "${log_file}" 2>&1 ||  {
    log_message "ERROR" "longairr seqtag" \
      "MaskPrimers failed." \
      "${log_file}"
    exit 1
  }
  # NOTE: Internal function (see longairr_utils.sh)
  update_progress ${current_step} ${constant_steps}

  #-----SPLIT by LOCI, VERBOSE-----#

  # Functionality to split and combine by specified --split-regex
  if [[ "${split}" == "TRUE" ]]; then
    # NOTE: Find the reference for third-party software 'presto [SplitSeq.py]' in '/vignette/software_references.md`
    SplitSeq.py group \
      -s "${matched_fasta}" \
      -f "${primer_field}" \
      --outname split \
      --outdir "${seqtag_tmp}" \
      >> "${log_file}" 2>&1 || {
        log_message "ERROR" "longairr seqtag" \
          "SplitSeq failed." \
          "${log_file}"
        exit 1
      }
    update_progress ${current_step} ${constant_steps}

    if [[ ${#split_regex[@]} -eq 0 ]]; then
      log_message "ERROR" "longairr seqtag" \
        "No values were provided through --split-regex." \
        "${log_file}"
      exit 1
    fi

    # Create one combined FASTA per requested split value.
    for split_value in "${split_regex[@]}"; do
      local split_dir="${seqtag_out}${split_value}/"
      local split_fasta="${split_dir}combined_${split_value}.fasta"
      local -a split_files=( "${seqtag_tmp}"/*"${split_value}"*.fasta )

      if [[ ! -e "${split_files[0]}" ]]; then
        log_message "ERROR" "longairr seqtag" \
          "No split files matched --split-regex value \"${split_value}\"." \
          "${log_file}"
        exit 1
      fi

      mkdir -p "${split_dir}"

      cat "${split_files[@]}" > "${split_fasta}" || {
        log_message "ERROR" "longairr seqtag" \
          "Failed to combine split files for \"${split_value}\"." \
          "${log_file}"
        exit 1
      }
    done
    update_progress ${current_step} ${constant_steps}
  fi

  local metadata_finished_at
  metadata_finished_at=$(date -Iseconds)

  #------STRUCTURED METADATA----#

  # Metadata generation is non-fatal.
  local metadata_input_sequences
  local metadata_matched_sequences
  local metadata_failed_sequences
  local metadata_counts_ready="TRUE"
  local resolved_run_root
  local split_regex_csv

  local -a metadata_optional_args=()

  metadata_input_sequences=$(seqkit stats -T "${input_seqs}" | awk 'NR==2 {print $4}') || {
    metadata_counts_ready="FALSE"
  }

  metadata_matched_sequences=$(seqkit stats -T "${matched_fasta}" | awk 'NR==2 {print $4}') || {
    metadata_counts_ready="FALSE"
  }

  if [[ -f "${failed_fasta}" ]]; then
    metadata_failed_sequences=$(seqkit stats -T "${failed_fasta}" | awk 'NR==2 {print $4}') || {
      metadata_counts_ready="FALSE"
    }

    metadata_optional_args+=(
      --count "failed_sequences=${metadata_failed_sequences}"
      --file "failed_fasta=${failed_fasta}"
    )
  fi

  if [[ "${split}" == "TRUE" ]]; then
    split_regex_csv=$(IFS=,; echo "${split_regex[*]}")

    metadata_optional_args+=(
      --parameter "split_regex=${split_regex_csv}"
    )

    for split_value in "${split_regex[@]}"; do
      local split_key
      local split_fasta
      local split_sequences

      split_key=$(echo "${split_value}" \
        | tr '[:upper:]' '[:lower:]' \
        | sed -E 's/[^a-z0-9]+/_/g; s/^_+//; s/_+$//')

      if [[ -z "${split_key}" ]]; then
        metadata_counts_ready="FALSE"
        continue
      fi

      split_fasta="${seqtag_out}${split_value}/combined_${split_value}.fasta"

      split_sequences=$(seqkit stats -T "${split_fasta}" | awk 'NR==2 {print $4}') || {
        metadata_counts_ready="FALSE"
      }

      metadata_optional_args+=(
        --count "split_${split_key}_sequences=${split_sequences}"
        --file "split_${split_key}_fasta=${split_fasta}"
      )
    done
  fi

  if [[ "${metadata_counts_ready}" == "TRUE" ]]; then
    if resolved_run_root=$(resolve_longairr_run_root \
      "${output}" \
      "${requested_run_root}" \
      "${LONGAIRR_VERSION}" \
      2>> "${log_file}"); then

      local metadata_record_id="run"
      local metadata_scope_type="run"
      local -a metadata_scope_args=()

      if [[ -n "${metadata_sample}" ]]; then
        metadata_record_id="${metadata_sample}"
        metadata_scope_type="sample"
        metadata_scope_args=(--sample "${metadata_sample}")
      fi

      local -a metadata_command=(
        longairr_metadata.py write-module
        --run-root "${resolved_run_root}"
        --module seqtag
        --longairr-version "${LONGAIRR_VERSION}"
        --record-id "${metadata_record_id}"
        --scope-type "${metadata_scope_type}"
        "${metadata_scope_args[@]}"
        --status success
        --started-at "${metadata_started_at}"
        --finished-at "${metadata_finished_at}"

        --parameter "window_length=${window_length}"
        --parameter "anchor_error=${max_error}"
        --parameter "primer_field=${primer_field}"
        --parameter "split=${split,,}"

        --count "input_sequences=${metadata_input_sequences}"
        --count "matched_sequences=${metadata_matched_sequences}"

        --file "input_anchor=${input_anchor}"
        --file "input_sequences=${input_seqs}"
        --file "matched_fasta=${matched_fasta}"
        --file "log=${log_file}"

        "${metadata_optional_args[@]}"
      )

      "${metadata_command[@]}" >> "${log_file}" 2>&1 || {
        log_message "WARNING" "longairr seqtag" \
          "Seqtag completed, but writing structured metadata failed." \
          "${log_file}"
      }
    else
      log_message "WARNING" "longairr seqtag" \
        "Seqtag completed, but the LongAIRR run root could not be initialized." \
        "${log_file}"
    fi
  else
    log_message "WARNING" "longairr seqtag" \
      "Seqtag completed, but metadata sequence counts could not be computed." \
      "${log_file}"
  fi
  update_progress ${current_step} ${constant_steps}


  # Info messages
  if [[ "${verbose}" == "TRUE" ]]; then
    log_message "INFO" "longairr seqtag" \
      "Output directory: ${seqtag_out}" \
      "${log_file}"
  fi
}


