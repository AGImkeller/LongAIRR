################################################################################
# LongAIRR collapse function
#
# Description:
#   Annotates Unique Molecular Identifiers (UMIs) in every read by matching to an anchor sequence.
#   Depending on the read structure the functionality differs:
#   BULK: Matches Linker and annotates UMI preceding the Linker
#   SPATIAL: Matches R1 and annotates UMI/SPBC trailing the R1 + additional SPBCUMI slot
#   In case longairr demux was performed (possible for bulk) matches are only checked for forward reads.
#   If longairr demux was not performed, failed-matches will be reverse-complemented and re-matched.
#   Builds a consensus per user-defined sequence group (valid: UMI or SPBCUMI).
#   Lastly, enumerates the reads and builds sequence headers
#   that contain GROUP / UMI / SPBC  and consensus count information.
#
# Arguments:
#   --demux <TRUE|FALSE>        Specify whether 'longairr demux' was performed (default: TRUE)
#   --library <TRUE|FALSE>      Specify used library preparation. Valid values: "visium", "visiumhd", "bulk". (default: "visium")"
#   --run-root <PATH>           Explicit LongAIRR run root (default: auto-detect from output)
#   --sample <VALUE>            Optional sample identifier for sample-level metadata
#   --verbose <TRUE|FALSE>      Whether to print runtime information (default: TRUE)" 
#   --h                         Show help / parameter documentation
#
#   --window-length <VALUE>     Window length for anchor-match search (default: 50)
#   --anchor-error <VALUE>      Maximal allowed mismatches for anchor match (default: 0.2)
#   --umi-length <VALUE>        Length of UMI sequence (default: 12 bp)
#
#   --spbc-error <VALUE>        Allowed fraction of mismatches between annotated SPBC and valid SPBCs (default: 0.0). Suggestion is <= 0.2, depending on the length of the SPBC.
#   --spbc-length <VALUE>       Length of the spatial barcodes (default: 16 bp)"
#
#   --group-field <VALUE>       Header slot used to collapse sequences into consensus (default: SPBCUMI)
#   --minl <VALUE>              Minimal sequence length threshold (default: no limit)
#   --maxl <VALE>               Maximal sequence length threshold (default: no limit)
#   -f | --adaptive-filter  TRUE | FALSE | Enable adaptive filtering based on read-length accumulation around a peak (default: TRUE)"
#   -g | --filter-min-size    VALUE (int)  | Only apply adaptive filtering to UMI groups with more than this many reads (default: 100)"
#   --bin-size       VALUE (int)  | Bin size for read-length accumulation detection used in adaptive filtering (default: 100)"
#   --peak-margin    VALUE (int)  | Relative margin around peak center in adpative filtering (default: 0.10)"   
#   --cons-gap <VALUE>          Cut-off for the frequency of allowed gap values for each position in the consensus sequence. Positions exceeding the threshold are deleted from the consensus (default: 0.5)"
#   --cons-error <VALUE>        Specifies the error rate of each read group (rate of mismatches from consensus) and removes groups exceeding the given error threshold. Error is calculated against final consensus (default: 0.2)"
#   --n-subsample <VALUE>       Minimum number of sequences needed to define a valid conseneus (default: 1)
#   --n-chunk <VALUE>           Number of (downsampled) umi groups sorted into a file (chunk) for parallel MSA-processing (default: 50)
#   --seed <VALUE>              Random seed for subsampling (default: 42)
#   --cjobs <VALUE>             Number of parallel jobs for MSA-processing using generated chunks (default: 6)
#
# Input:
#   input_anchor     | Path to FASTA file containing UDI anchors used for multiplexing
#   input_seqs       | Path to FASTA file containing (filtered) sequences
#   output           | Path to the output directory
#  --visium-spbc             | [FOR SPATIAL -VISIUM V1- RUNS] TXT file containing list of sequence and coordinates for 10X Visium spatial barcodes"
#  --hd-spbc1 and --hd-spbc2 | [FOR SPATIAL -VISIUM HD 3'- RUNS] TXT files containing list of sequence for !0x Visium HD 3' SPBC1 and SPBC2 respetively"
#
# Output:
#   Files are saved in 'output/collapse/' and 'output/collapse/tmp/'
#   
#   The function generates multiple outputs:
#     - FASTA file containing every read and the annotated UMI: 'longairr_umi.fasta'
#     - FASTA file containing consensus sequences per specified group-field (UMI or SPBCUMI): '4_longairr_consensus.fasta'
#
################################################################################
collapse() {

  # parameters
  local input_anchor
  local input_seqs
  local output
  local spbc_file
  local bc1_file
  local bc2_file
  local longairr_whitelist_index

  local requested_run_root=""
  local metadata_sample=""

  local demux="TRUE"
  local library="visium"
  local verbose="TRUE"

  local window_length=1200
  local max_error=0.2
  
  #visium v1 specific
  local umi_length=12
  local spbc_error=0.0
  local spbc_length=16

  # visium hd 3' specific
  local hd_umi_base_length=9
  local hd_offsets="0,1,2"
  local hd_spbc_lengths="auto"
  local hd_bins="002um"

  local min_length=-1 # seqkit default (no limit)
  local max_length=-1
  local group_field
  local adaptive_filter="TRUE"
  local min_group_size=5
  local bin_size=100
  local peak_margin=0.05
  
  local n_cons=1 # no input parameter
  local cons_gap=0.5
  local cons_error=0.2
  local umi_group_n=999999
  local umi_per_chunk=50 
  local seed=1
  local parallel_cjobs=6

  # progress bar
  local current_step=0
  local umi_steps=11
  
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --demux)
        demux=$(echo "$2" | tr '[:lower:]' '[:upper:]')
        # NOTE: Internal function [see longairr_utils.sh]
        validate_boolean_parameters '--demux' "${demux}"
        shift 2
        ;;
      --library)
        library=$(echo "$2" | tr '[:upper:]' '[:lower:]')
        shift 2
        ;;
      --verbose)
        verbose=$(echo "$2" | tr '[:lower:]' '[:upper:]')
        validate_boolean_parameters '--verbose' "${verbose}"
        shift 2
        ;;
      --run-root)
        requested_run_root="$2"
        shift 2
        ;;
      --sample)
        metadata_sample="$2"
        shift 2
        ;;
      -h|--help)
        show_help_collapse
        exit 0
        ;;
      --window-length)
        window_length=$2
        shift 2
        ;;
      --anchor-error)
        max_error=$2
        shift 2
        ;;
      --umi-length)
        umi_length=$2
        shift 2
        ;;
      --spbc-error)
        spbc_error=$2
        shift 2
        ;;
      --spbc-length)
        spbc_length=$2
        shift 2
        ;;
      --minl)
        min_length=$2
        shift 2
        ;;
      --maxl)
        max_length=$2
        shift 2
        ;;
      --group-field)
        group_field="$2"
        shift 2
        ;;
      -f|--adaptive-filter)
        adaptive_filter=$(echo "$2" | tr '[:lower:]' '[:upper:]')
        validate_boolean_parameters '--adaptive-filter' "${adaptive_filter}"
        shift 2
        ;;
      -g|--filter-min-size)
        min_group_size=$2
        shift 2
        ;;
      --bin-size)
        bin_size=$2
        shift 2
        ;;
      --peak-margin)
        peak_margin=$2
        shift 2
        ;;
      --cons-gap)
        cons_gap=$2
        shift 2
        ;;
      --cons-error)
        cons_error=$2
        shift 2
        ;;
      --n-subsample)
        umi_group_n=$2
        shift 2
        ;;
      --n-chunk)
        umi_per_chunk=$2
        shift 2
        ;;
      --seed)
        seed=$2
        shift 2
        ;;
      --cjobs)
        parallel_cjobs=$2
        shift 2
        ;;
      --visium-spbc)
        spbc_file="$2"
        shift 2
        ;;
      --hd-spbc1)
        bc1_file="$2"
        shift 2
        ;;
      --hd-spbc2)
        bc2_file="$2"
        shift 2
        ;;
      --hd-spbc-index)
        longairr_whitelist_index="$2"
        shift 2
        ;;
      *) 
        if [[ -z "${input_anchor}" ]]; then
          input_anchor="$1"
        elif [[ -z "${input_seqs}" ]]; then
          input_seqs="$1"
        elif [[ -z "${output}" ]]; then
          output="$1"
        else
          echo "Unexpected argument \"$1\". For detailed usage, run 'longairr collapse --help'."
          exit 1
        fi
        shift
        ;;
    esac
  done

  if [[ -z "${input_seqs}" || -z "${input_anchor}" || -z "${output}" ]]; then
    echo "ERROR: Missing required arguments: all input and output parameters must be specified."
    echo "For detailed usage, run 'longairr collapse --help'."
    exit 1
  fi

  if [[ ! -d "${output}" ]]; then
    echo "ERROR: Specified output path \"${output}\" is not a valid directory."
    echo "Ensure the path exists and is writable."
    exit 1
  fi

  #-----LOG FILE and PROGRESS BAR-----#

  local log_path="${output%/}/collapse/"
  mkdir -p "${log_path}"
  local log_file="${log_path}longairr_collapse.log"

  echo -e "\n###############\n#longairr collapse#\n###############\n" | tee -a "${log_file}"

  # NOTE: Internal function (see longairr_utils.sh)
  progress_bar ${current_step} ${umi_steps}

  #--------INPUT CHECKS--------#

  if [[ ! -f "${input_seqs}" ]]; then
    log_message "ERROR" "longairr collapse" \
      "Specified input sequence file does not exist. For detailed usage, run 'longairr collapse --help'." \
      "${log_file}"
    exit 1
  elif [[ "${input_seqs}" != *.fasta ]]; then
    log_message "ERROR" "longairr collapse" \
      "Input file \"${input_seqs}\" must have a valid FASTA extension (.fasta)." \
      "${log_file}"
    exit 1
  fi

  if [[ ! -f "${input_anchor}" ]]; then
    log_message "ERROR" "longairr collapse" \
      "Specified input anchor file does not exist. For detailed usage, run 'longairr collapse --help'." \
      "${log_file}"
    exit 1
  elif [[ "${input_anchor}" != *.fasta ]]; then
    log_message "ERROR" "longairr collapse" \
      "Input file \"${input_anchor}\" must have a valid FASTA extension (.fasta)." \
      "${log_file}"
    exit 1
  fi

  # Set up collapse output- and intermediate directories
  local collapse_out="${output%/}/collapse/"
  local collapse_tmp="${collapse_out}tmp/"
  local tmp_annotate="${collapse_tmp}1_annotate_umis_spbc/"
  local tmp_group="${collapse_tmp}2_filt_group_sub_cons/"

  mkdir -p "${collapse_tmp}"

  #--------LIBRARY / GROUP FIELD DEFAULTS & VALIDATION--------#

  # validate library
  if [[ "${library}" != "bulk" && "${library}" != "visium" && "${library}" != "visiumhd" ]]; then
    log_message "ERROR" "longairr collapse" \
      "Invalid --library '${library}'. Allowed values are 'bulk', 'visium', or 'visiumhd'." \
      "${log_file}"
    exit 1
  fi

  # set sensible default group_field if user did not provide one
  if [[ -z "${group_field}" ]]; then
    if [[ "${library}" == "bulk" ]]; then
      group_field="UMI"
    elif [[ "${library}" == "visium" ]]; then
      group_field="SPBCUMI"
    elif [[ "${library}" == "visiumhd" ]]; then
      group_field="UMISPBCID"
    fi
  fi

  # validate allowed group_field values
  if [[ "${group_field}" != "UMI" && "${group_field}" != "SPBCUMI" && "${group_field}" != "UMISPBCID" ]]; then
    log_message "ERROR" "longairr collapse" \
      "Invalid --group-field '${group_field}'. Allowed values are 'UMI', 'SPBCUMI', or 'UMISPBCID'." \
      "${log_file}"
    exit 1
  fi

  # validate group_field compatibility with selected library
  if [[ "${library}" == "bulk" ]]; then
    if [[ "${group_field}" != "UMI" ]]; then
      log_message "ERROR" "longairr collapse" \
        "--group-field '${group_field}' is not valid for bulk mode. Allowed value is 'UMI'." \
        "${log_file}"
      exit 1
    fi

  elif [[ "${library}" == "visium" ]]; then
    if [[ "${group_field}" != "UMI" && "${group_field}" != "SPBCUMI" ]]; then
      log_message "ERROR" "longairr collapse" \
        "--group-field '${group_field}' is not valid for visium mode. Allowed values are 'UMI' or 'SPBCUMI'." \
        "${log_file}"
      exit 1
    fi

  elif [[ "${library}" == "visiumhd" ]]; then
