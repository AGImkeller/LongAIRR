################################################################################
# LongAIRR airr function
#
# Description:
#   Performs V(D)J gene annotation using IgBLAST, assigning germline 
#   gene segments to UMI-annotated-consensus sequences. Optionally allows filtering of 
#   non-productive and non-heavy sequences if specified. Transforms sequence data into
#   AIRR-format conform tabular data.
#
# Arguments:
#   --ph        <TRUE|FALSE>  Generate additional files with non-productive 
#                             and non-heavy Ig sequences removed (default: TRUE). 
#                             Non-heavy filtering is applied only if '--loci ig' is set.
#   --loci      <ig|tr>       Specifies the loci for V(D)J gene annotation. 
#                             Valid values: 'ig' (immunoglobulin) or 'tr' (TCR). (default: ig)
#   --run-root <PATH>       Explicit LongAIRR run root (default: auto-detect from output)
#   --sample <VALUE>        Optional sample identifier for sample-level metadata
#   --verbose   <TRUE|FALSE>  Whether to print detailed runtime information (default: TRUE)
#   -h, --help                Show this help message and exit
#
# Input:
#   inputdir_igblast    | Path to directory containing IgBLAST database
#   inputdir_germlines  | Path to directory containing germline database
#   input_seqs          | Path to FASTA file containing UMI-annotated sequences
#   outdir              | Path to output directory
#
# Output:
#   Files are saved in 'output/airr/'
#
#   The function generates multiple outputs:
#     - Annotated AIRR-compliant TSV file: i.e.: 'ig_ph_parse-select.tsv'
#
################################################################################
airr() {

  # parameters
  local input_igblast
  local input_germlines
  local input_seqs
  local output

  local requested_run_root=""
  local metadata_sample=""

  local filter_ph="TRUE"
  local valid_loci="ig"
  
  local verbose="TRUE"
  # progress bar
  local airr_steps=3
  local current_step=0

  while [[ $# -gt 0 ]]; do
    case "$1" in
      --ph)
        filter_ph=$(echo "$2" | tr '[:lower:]' '[:upper:]')
        # NOTE: Internal function [see longairr_utils.sh]
        validate_boolean_parameters '--ph' "${filter_ph}"
        shift 2
        ;;
      --loci)
        if [[ -n "${2:-}" ]]; then
          valid_loci=$(echo "$2" | tr '[:upper:]' '[:lower:]')
          shift 2
        else
          echo "--loci option requires an argument." >&2
          exit 1
        fi
        ;;
      --run-root)
        requested_run_root="$2"
        shift 2
        ;;
      --sample)
        metadata_sample="$2"
        shift 2
        ;;
      --verbose)
          verbose=$(echo "$2" | tr '[:lower:]' '[:upper:]')
          validate_boolean_parameters '--verbose' "${verbose}"
          shift 2
          ;;
      -h|--help)
          show_help_airr
          exit 0
          ;;
      *)
        if [[ -z "${input_igblast}" ]]; then
          input_igblast="$1"
        elif [[ -z "${input_germlines}" ]]; then
          input_germlines="$1"
        elif [[ -z "$input_seqs" ]]; then
          input_seqs="$1"
        elif [[ -z "$output" ]]; then
          output="$1"
        else
          echo "Unexpected argument \"$1\". For detailed usage, run 'longairr airr --help'."
          exit 1
        fi
        shift
        ;;
      esac
  done

  if [[ -z "${input_seqs}" || -z "${input_igblast}" || -z "${input_germlines}" || -z "${output}" ]]; then
    echo "ERROR: Missing required arguments: all input and output parameters must be specified."
    echo "For detailed usage, run 'longairr airr --help'."
    exit 1
  fi

  if [[ ! -d "${output}" ]]; then
    echo "ERROR: Specified output path \"${output}\" is not a valid directory."
    echo "Ensure the path exists and is writable."
    exit 1
  fi

  #-----LOG FILE and PROGRESS BAR-----#

    # AIRR final outputs share one module directory, while temporary files and
  # internal logs are separated by locus so IG and TR can run in parallel.
  local airr_out="${output%/}/airr/"
  local airr_tmp="${airr_out}tmp/${valid_loci}/"
  local log_file="${airr_out}longairr_airr_${valid_loci}.log"

  mkdir -p "${airr_tmp}"

  echo -e "\n###############\n#longairr airr#\n###############\n" | tee -a "${log_file}"

  # NOTE: Internal function (see longairr_utils.sh)
  progress_bar ${current_step} ${airr_steps}

  #-----INPUT CHECKS-----#

  if [[ ! -f "${input_seqs}" ]]; then
    log_message "ERROR" "longairr airr" \
      "Specified input sequence file does not exist. For detailed usage, run 'longairr airr --help'." \
      "${log_file}"
    exit 1
  elif [[ "${input_seqs}" != *.fasta ]]; then
    log_message "ERROR" "longairr airr" \
      "Input file \"${input_seqs}\" must have a valid FASTA extension (.fasta)." \
      "${log_file}"
    exit 1
  fi

  if [[ ! -d "${input_igblast}" ]]; then
    log_message "ERROR" "longairr airr" \
      "Specified igblast database path \"${input_igblast}\" is not a valid directory." \
      "${log_file}"
    exit 1
  fi

  if [[ ! -d "${input_germlines}" ]]; then
    log_message "ERROR" "longairr airr" \
      "Specified germlines database path \"${input_germlines}\" is not a valid directory." \
      "${log_file}"
    exit 1
  fi

  if [[ ! "${valid_loci}" == "ig" && ! "${valid_loci}" == "tr" ]]; then
    log_message "ERROR" "longairr airr" \
      "Invalid value for the --loci parameter. Valid values are: ig OR tr." \
      "${log_file}"
    exit 1
  fi

  #--------FUNCTIONALITY-------#

  local metadata_started_at
  metadata_started_at=$(date -Iseconds)

  # Define file paths
  local fasta_name
  local fmt_in
  local db_pass
  local productive_out="${airr_out}${valid_loci}_p_parse-select.tsv"
  local productive_heavy_out="${airr_out}${valid_loci}_ph_parse-select.tsv"

  fasta_name=$(basename "${input_seqs}" .fasta)
  fmt_in="${airr_tmp}${fasta_name}_igblast.fmt7"

  if [[ "${filter_ph}" == "TRUE" ]]; then
    db_pass="${airr_tmp}${valid_loci}_db-pass.tsv"
  else
    db_pass="${airr_out}${valid_loci}_db-pass.tsv"
  fi

  # Assign V(D)J genes using igblast
  AssignGenes.py igblast -s "${input_seqs}" -b "${input_igblast}" --organism human --loci "${valid_loci}" --format blast --cdb imgt_human_"${valid_loci}"_c --outdir "${airr_tmp}" >> "${log_file}" 2>&1 || {
    log_message "ERROR" "longairr airr" \
      "AssignGenes failed." \
      "${log_file}"
    exit 1
  }
  # NOTE: Internal function (see longairr.sh)
  update_progress ${current_step} ${airr_steps}

  if [[ "${filter_ph}" == "TRUE" ]]; then

    #local productive_in="${airr_tmp}${valid_loci}_db-pass.tsv"
    #local heavy_in="${airr_out}${valid_loci}_p_parse-select.tsv"

    # NOTE: Find the reference for third-party software 'changeo [MakeDb.py]' in '/vignette/software_references.md`
    MakeDb.py igblast -s "${input_seqs}" -i "${fmt_in}" --format airr --extended -r "${input_germlines}" --outdir "${airr_tmp}" --outname "${valid_loci}" >> "${log_file}" 2>&1 || {
      log_message "ERROR" "longairr airr" \
        "MakeDb igblast filter_p failed." \
        "${log_file}"
      exit 1
    }

    # Filter out all non-productive sequences
    # NOTE: Find the reference for third-party software 'changeo [ParseDb.py]' in '/vignette/software_references.md`
    ParseDb.py select -d "${db_pass}" -f productive -u T --outname "${valid_loci}_p" --outdir "${airr_out}" >> "${log_file}" 2>&1 || {
      log_message "ERROR" "longairr airr" \
        "ParseDb igblast filter_p failed." \
        "${log_file}"
      exit 1
    }

    # Filter out all non-IGH sequences (for 'ig' loci)
    if [[ "${valid_loci}" == "ig" ]]; then
      ParseDb.py select -d "${productive_out}" -f v_call -u IGHV --regex --outname "${valid_loci}_ph" --outdir "${airr_out}" >> "${log_file}" 2>&1 || {
        log_message "ERROR" "longairr airr" "ParseDb igblast filter_h failed." "${log_file}"
        exit 1
      }
    fi
    update_progress ${current_step} ${airr_steps}

  else
    # Transform to airr format without filtering
    # NOTE: Find the reference for third-party software 'changeo [MakeDb.py]' in '/vignette/software_references.md`
    MakeDb.py igblast -s "${input_seqs}" -i "${fmt_in}" --format airr --extended -r "${input_germlines}" --outdir "${airr_out}" --outname "${valid_loci}" >> "${log_file}" 2>&1 || {
      log_message "ERROR" "longairr airr" \
        "MakeDb igblast no_filter failed." \
        "${log_file}"
      exit 1
    }
    update_progress "${current_step}" "${airr_steps}"
  fi

  local metadata_finished_at
  metadata_finished_at=$(date -Iseconds)

  #------STRUCTURED METADATA----#

  # Metadata generation is non-fatal
  local metadata_input_sequences
  local metadata_airr_sequences
  local metadata_productive_sequences
  local metadata_productive_heavy_sequences
  local metadata_counts_ready="TRUE"
  local resolved_run_root

  local -a metadata_optional_args=()

  metadata_input_sequences=$(seqkit stats -T "${input_seqs}" | awk 'NR==2 {print $4}') || {
    metadata_counts_ready="FALSE"
  }

  if [[ -f "${db_pass}" ]]; then
    metadata_airr_sequences=$(awk 'END {print (NR > 0 ? NR - 1 : 0)}' "${db_pass}") || {
      metadata_counts_ready="FALSE"
    }
  else
    metadata_counts_ready="FALSE"
  fi

  if [[ "${filter_ph}" == "TRUE" ]]; then
    if [[ -f "${productive_out}" ]]; then
      metadata_productive_sequences=$(awk 'END {print (NR > 0 ? NR - 1 : 0)}' "${productive_out}") || {
        metadata_counts_ready="FALSE"
      }

      metadata_optional_args+=(
        --count "productive_sequences=${metadata_productive_sequences}"
        --file "productive_airr_tsv=${productive_out}"
      )
    else
      metadata_counts_ready="FALSE"
    fi

    if [[ "${valid_loci}" == "ig" ]]; then
      if [[ -f "${productive_heavy_out}" ]]; then
        metadata_productive_heavy_sequences=$(awk 'END {print (NR > 0 ? NR - 1 : 0)}' "${productive_heavy_out}") || {
          metadata_counts_ready="FALSE"
        }

        metadata_optional_args+=(
          --count "productive_heavy_sequences=${metadata_productive_heavy_sequences}"
          --file "productive_heavy_airr_tsv=${productive_heavy_out}"
        )
      else
        metadata_counts_ready="FALSE"
      fi
    fi
  fi

  if [[ "${metadata_counts_ready}" == "TRUE" ]]; then
    if resolved_run_root=$(resolve_longairr_run_root \
      "${output}" \
      "${requested_run_root}" \
      "${LONGAIRR_VERSION}" \
      2>> "${log_file}"); then

      local metadata_record_id="${valid_loci}"
      local metadata_scope_type="locus"
      local -a metadata_scope_args=(
        --locus "${valid_loci}"
      )

      if [[ -n "${metadata_sample}" ]]; then
        metadata_record_id="${metadata_sample}_${valid_loci}"
        metadata_scope_type="sample_locus"
        metadata_scope_args=(
          --sample "${metadata_sample}"
          --locus "${valid_loci}"
        )
      fi

      if [[ "${valid_loci}" == "ig" ]]; then
        metadata_optional_args+=(
          --parameter "filter_heavy=${filter_ph,,}"
        )
      fi

      local -a metadata_command=(
        longairr_metadata.py write-module
        --run-root "${resolved_run_root}"
        --module airr
        --longairr-version "${LONGAIRR_VERSION}"
        --record-id "${metadata_record_id}"
        --scope-type "${metadata_scope_type}"
        "${metadata_scope_args[@]}"
        --status success
        --started-at "${metadata_started_at}"
        --finished-at "${metadata_finished_at}"

        --parameter "locus=${valid_loci}"
        --parameter "filter_productive=${filter_ph,,}"
        --parameter "organism=human"
        --parameter "igblast_format=blast"
        --parameter "airr_format=airr"
        --parameter "constant_database=imgt_human_${valid_loci}_c"

        --count "input_sequences=${metadata_input_sequences}"
        --count "airr_sequences=${metadata_airr_sequences}"

        --file "input_sequences=${input_seqs}"
        --file "igblast_database=${input_igblast}"
        --file "germline_database=${input_germlines}"
        --file "igblast_fmt7=${fmt_in}"
        --file "airr_tsv=${db_pass}"
        --file "log=${log_file}"

        "${metadata_optional_args[@]}"
      )

      "${metadata_command[@]}" >> "${log_file}" 2>&1 || {
        log_message "WARNING" "longairr airr" \
          "AIRR processing completed, but writing structured metadata failed." \
          "${log_file}"
      }
    else
      log_message "WARNING" "longairr airr" \
        "AIRR processing completed, but the LongAIRR run root could not be initialized." \
        "${log_file}"
    fi
  else
    log_message "WARNING" "longairr airr" \
      "AIRR processing completed, but metadata counts could not be computed." \
      "${log_file}"
  fi
  update_progress ${current_step} ${airr_steps}

  #--------VERBOSE--------#

  if [[ "${verbose}" == "TRUE" ]]; then
    log_message "INFO" "longairr airr" \
      "Output directory: ${airr_out}" \
      "${log_file}"
  fi
}


