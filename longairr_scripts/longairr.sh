################################################################################
# LongAIRR filter function
#
# Description:
#   Filters nanopore FASTQ sequences based on quality and length thresholds. 
#   It processes the input data, filters sequences according to user-defined 
#   parameters, and generates FASTA/FASTQ outputs. A QC report is created using 
#   NanoPlot to assess the quality of the filtered reads.
#
# Arguments:
#   --min-qual <VALUE>        Minimum sequence quality threshold (default: no limit)
#   --minl <VALUE>            Minimum sequence length threshold (default: no limit)
#   --maxl <VALUE>            Maximum sequence length threshold (default: no limit)
#   --run-root <PATH>         Explicit LongAIRR run root (default: auto-detect from output)
#   --verbose <TRUE|FALSE>    Whether to print detailed runtime information (default: TRUE)
#   -h, --help                Show this help message and exit
#
# Input:
#   input       | Path to the input FASTQ file (.fastq file)
#   output      | Path to the output directory for filtered sequences and QC reports
#
# Output:
#   Files are saved in 'output/filter_qc/'
#   
#   The function generates multiple outputs:
#     - Filtered FASTQ file: `longairr_filtered.fastq`
#     - Filtered FASTA file: `longairr_filtered.fasta`
#     - A QC report generated by NanoPlot in `output/filter_qc/qc_report/filtered/`
#
################################################################################
filter() {

  # parameters
  local input
  local output
  
  local min_qual=-1 # seqkit default (no limit)
  local min_length=-1 
  local max_length=-1
  local requested_run_root="" 

  local verbose="TRUE"
  # progress bar
  local current_step=0
  local filter_steps=4

  while [[ $# -gt 0 ]]; do
    case "$1" in
      --min-qual)
        min_qual=$2
        shift 2
        ;;
      --minl)
        min_length=$2
        shift 2
        ;;
      --maxl)
        max_length=$2
        shift 2
        ;;
      --run-root)
        requested_run_root="$2"
        shift 2
        ;;
      --verbose)
        verbose=$(echo "$2" | tr '[:lower:]' '[:upper:]')
        # NOTE: Internal function (see longairr_utils.sh)
        validate_boolean_parameters '--verbose' "${verbose}"
        shift 2
        ;;
      -h|--help)
        show_help_filter
        exit 0
        ;;
      *)
        if [[ -z "${input}" ]]; then
          input="$1"
        elif [[ -z "${output}" ]]; then
          output="$1"
        else
          echo "Unexpected argument \"$1\". For detailed usage, run 'longairr filter --help'."
          exit 1
        fi
        shift
        ;;
    esac
  done

  #-------Input / output checks 

  if [[ -z "${input}" || -z "${output}" ]]; then
    echo "ERROR: Missing required arguments: all input and output parameters must be specified."
    echo "For detailed usage, run 'longairr filter --help'."
    exit 1
  fi

  if [[ ! -d "${output}" ]]; then
    echo "ERROR: Specified output path \"${output}\" is not a valid directory."
    echo "Ensure the path exists and is writable."
    exit 1
  fi

  #---LOG FILE + PROGRESS BAR--#

  local log_path="${output%/}/filter_qc/"
  mkdir -p "${log_path}"
  local log_file="${log_path}longairr_filter.log"

  echo -e "\n#################\n#longairr filter#\n#################\n" | tee -a "${log_file}"

  # NOTE: Internal function (see longairr_utils.sh)
  progress_bar ${current_step} ${filter_steps}

  #--------Additional checks--------#

  if [[ ! -f "${input}" ]]; then
    log_message "ERROR" "longairr filter" \
      "Specified input file does not exist. For detailed usage, run 'longairr filter --help'." \
      "${log_file}"
    exit 1
  elif [[ "${input}" != *.fastq && "${input}" != *.fq ]]; then
    log_message "ERROR" "longairr filter" \
      "Input file \"${input}\" must have a valid FASTQ extension (.fastq or .fq)." \
      "${log_file}"
    exit 1
  fi

  # Set up filter output- and intermediate directories
  local qc_outdir="${output%/}/filter_qc/"
  local nanoplot_output_dir="${qc_outdir}qc_report/filtered/"
  mkdir -p "${qc_outdir}" "${nanoplot_output_dir}"

  #--------FUNCTIONALITY-------#

  local metadata_started_at
  metadata_started_at=$(date -Iseconds)

  # Define file paths
  local filtered_fastq="${qc_outdir}longairr_filtered.fastq"
  local filtered_fasta="${qc_outdir}longairr_filtered.fasta"

  # Filter sequences on specified length and quality parameters
  # NOTE: Find the reference for third-party software 'seqkit' in '/vignette/software_references.md`
  seqkit seq -m ${min_length} -M ${max_length} -Q ${min_qual} "${input}" -o "${filtered_fastq}" >> "${log_file}" 2>&1 || {
    log_message "ERROR" "longairr filter" \
      "Failed to filter sequences while executing: seqkit seq -m \"${min_length}\" -M \"${max_length}\" -Q \"${min_qual}\" \"${input}\" -o \"${filtered_fastq}\"" \
      "${log_file}"
    exit 1
  }
  # NOTE: Internal function (see longairr_utils.sh)
  update_progress ${current_step} ${filter_steps}

  # Fastq to fasta
  # NOTE: Find the reference for third party software 'seqkit' in '/vignette/software_references.md`
  seqkit fq2fa "${filtered_fastq}" -o "${filtered_fasta}" >> "${log_file}" 2>&1 || {
    log_message "ERROR" "longairr filter" \
      "Failed to convert FASTQ to FASTA while executing: seqkit fq2fa \"${filtered_fastq}\" -o \"${filtered_fasta}\"" \
      "${log_file}"
    exit 1
  }
  update_progress ${current_step} ${filter_steps}

  # Generate QC report
  # NOTE: Find the reference for third party software 'NanoPlot' in '/vignette/software_references.md`
  NanoPlot --fastq "${filtered_fastq}" --outdir "${nanoplot_output_dir}" >> "${log_file}" 2>&1 || {
    log_message "ERROR" "longairr filter" \
      "QC report generation failed while executing: NanoPlot --fastq \"${filtered_fastq}\" --outdir \"${nanoplot_output_dir}\"" \
      "${log_file}"
    exit 1
  }
  update_progress ${current_step} ${filter_steps}


  local metadata_finished_at
  metadata_finished_at=$(date -Iseconds)


  #------STRUCTURED METADATA----#

  # Metadata generation is non-fatal
  local metadata_input_reads
  local metadata_filtered_reads
  local resolved_run_root
  local metadata_counts_ready="TRUE"

  metadata_input_reads=$(seqkit stats -T "${input}" | awk 'NR==2 {print $4}') || {
    metadata_counts_ready="FALSE"
  }

  metadata_filtered_reads=$(seqkit stats -T "${filtered_fasta}" | awk 'NR==2 {print $4}') || {
    metadata_counts_ready="FALSE"
  }

  if [[ "${metadata_counts_ready}" == "TRUE" ]]; then
    if resolved_run_root=$(resolve_longairr_run_root \
      "${output}" \
      "${requested_run_root}" \
      "${LONGAIRR_VERSION}" \
      2>> "${log_file}"); then

      longairr_metadata.py write-module \
        --run-root "${resolved_run_root}" \
        --module filter \
        --longairr-version "${LONGAIRR_VERSION}" \
        --record-id run \
        --scope-type run \
        --status success \
        --started-at "${metadata_started_at}" \
        --finished-at "${metadata_finished_at}" \
        --parameter "min_quality=${min_qual}" \
        --parameter "min_length=${min_length}" \
        --parameter "max_length=${max_length}" \
        --count "input_reads=${metadata_input_reads}" \
        --count "filtered_reads=${metadata_filtered_reads}" \
        --file "input_fastq=${input}" \
        --file "filtered_fastq=${filtered_fastq}" \
        --file "filtered_fasta=${filtered_fasta}" \
        --file "log=${log_file}" \
        --file "nanoplot_report=${nanoplot_output_dir}NanoPlot-report.html" \
        >> "${log_file}" 2>&1 || {
          log_message "WARNING" "longairr filter" \
            "Filter completed, but writing structured metadata failed." \
            "${log_file}"
        }
    else
      log_message "WARNING" "longairr filter" \
        "Filter completed, but the LongAIRR run root could not be initialized." \
        "${log_file}"
    fi
  else
    log_message "WARNING" "longairr filter" \
      "Filter completed, but metadata read counts could not be computed." \
      "${log_file}"
  fi
  update_progress ${current_step} ${filter_steps}
  
  
  #--------VERBOSE-----#

  # Info messages
  if [[ "${verbose}" == "TRUE" ]]; then
    log_message "INFO" "longairr filter" \
      "Output directory for filtered files: ${filtered_fasta}" \
      "${log_file}"
    
    log_message "INFO" "longairr filter" \
      "Output directory for QC: ${nanoplot_output_dir}" \
      "${log_file}"
  fi
}


