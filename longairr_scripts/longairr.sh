################################################################################
# LongAIRR basecall function
#
# Description:
#   Performs basecall on nanopore data using Dorado duplex basecaller.
#   It processes both simplex and/or duplex reads, generates FASTA/FASTQ outputs, 
#   and creates a QC report using NanoPlot.
#
# Arguments:
#   --min-qual <VALUE>        Minimal sequence quality threshold (default: no limit)
#   --model <VALUE>           basecall model to use (default: sup)
#   --cuda <VALUE>            GPU to use (default: cuda:all)
#   --batch <VALUE>           Basecaller limit on how many reads are processed at the same time (default: 64)
#   --simplex <TRUE|FALSE>    Whether to process simplex reads (default: TRUE)
#   --duplex <TRUE|FALSE>     Whether to process duplex reads (default: TRUE)
#   --fasta <TRUE|FALSE>      Whether to generate FASTA output (default: TRUE)
#   --verbose <TRUE|FALSE>    Whether to print additional runtime information (default: TRUE)
#   -h, --help                Show this help message and exit
#
# Input:
#   input               | Path to directory containing nanopore POD5 files
#   output              | Path to the output directory
#
# Output:
#   Files are saved in 'outdir/basecall/'
#  
#   The function generates multiple outputs:
#     - BAM files for raw and simplex-/duplex reads
#     - FASTQ and/or FASTA files (based on user options)
#     - A QC report generated by NanoPlot
#
################################################################################
basecall() {
  
  # parameters
  local input
  local output

  local min_qual=0
  local basecall_model="sup"
  local cuda="cuda:all"
  local batch_size=64
  local simplex="TRUE"
  local duplex="TRUE"
  local fasta="TRUE"

  local verbose="TRUE"

  while [[ $# -gt 0 ]]; do
    case "$1" in
      --min-qual|-q)
        min_qual=$2
        shift 2
        ;;
      --model)
        basecall_model="$2"
        shift 2
        ;;
      --cuda)
        cuda="$2"
        shift 2
        ;;
      --batch)
        batch_size=$2
        shift 2
        ;;
      --simplex)
        simplex=$(echo "$2" | tr '[:lower:]' '[:upper:]')
        # NOTE: Internal function (see longairr_utils.sh)
        validate_boolean_parameters '--simplex' "${simplex}"
        shift 2
        ;;
      --duplex)
        duplex=$(echo "$2" | tr '[:lower:]' '[:upper:]')
        validate_boolean_parameters '--duplex' "${duplex}"
        shift 2
        ;;
      --fasta)
        fasta=$(echo "$2" | tr '[:lower:]' '[:upper:]')
        validate_boolean_parameters '--fasta' "${fasta}"
        shift 2
        ;;
      --verbose)
        verbose=$(echo "$2" | tr '[:lower:]' '[:upper:]')
        validate_boolean_parameters '--verbose' "${verbose}"
        shift 2
        ;;
      -h|--help)
        show_help_basecall
        exit 0
        ;;
      *)
        if [[ -z "${input}" ]]; then
          input="$1"
        elif [[ -z "${output}" ]]; then
          output="$1"
        else
          echo "Unexpected argument \"$1\". For detailed usage, run 'longairr basecall --help'."
          exit 1
        fi
        shift
        ;;
    esac
  done
  
  #----------LOG FILE----------#

  local log_path="${output}basecall/"
  mkdir -p "${log_path}"
  local log_file="${log_path}longairr_basecall.log"

  echo -e "\n######################\n#longairr basecall#\n######################\n" | tee -a "${log_file}"

  #--------INPUT CHECKS--------#

  if [[ -z "${input}" || -z "${output}" ]]; then
    log_message "ERROR" "longairr basecall" \
      "Missing required arguments: input and output must be specified." \
      "${log_file}"
    exit 1
  fi

  # Set up basecall output- and intermediate directories
  if [[ -d "${output}" ]]; then
    basecall_dir="${output%/}/basecall/"
    tmp_dir="${basecall_dir}tmp/"
    nanoplot_output_dir="${output%/}/filter_qc/qc_report/raw/"

    mkdir -p "${basecall_dir}" "${tmp_dir}" "${nanoplot_output_dir}"
  else
    log_message "ERROR" "longairr basecall" \
      "Specified output path \"${output}\" is not a valid directory." \
      "${log_file}"
    exit 1
  fi

  #--------FUNCTIONALITY-------#

  # Define file paths
  basecall_bam="${tmp_dir}/dorado.bam"
    
  simplex_bam="${tmp_dir}/simplex.bam"
  simplex_fastq="${basecall_dir}/simplex.fastq"
  simplex_fasta="${basecall_dir}/simplex.fasta"

  duplex_bam="${tmp_dir}/duplex.bam"
  duplex_fastq="${basecall_dir}/duplex.fastq"
  duplex_fasta="${basecall_dir}/duplex.fasta"

  combined_fastq="${basecall_dir}/simplex_duplex.fastq"
  combined_fasta="${basecall_dir}/simplex_duplex.fasta"

  qc_file=""

  if [[ -f "${basecall_bam}" ]]; then
    log_message "INFO" "longairr basecall" \
      "basecall was not performed. Results already exist: \"${basecall_bam}\" Choose different output directory to perform basecall again." \
      "${log_file}"
  else
    # NOTE: Find the reference for third-party software 'dorado duplex' in '/vignette/software_references.md`
    dorado duplex -x "${cuda}" --min-qscore ${min_qual} -b ${batch_size} "${basecall_model}" "${input}" -r > "${basecall_bam}" 2>> "${log_file}" || {   
      log_message "ERROR" "longairr basecall" \
        "basecall failed while executing: dorado duplex -x \"${cuda}\" --min-qscore \"${min_qual}\" \"${basecall_model}\" \"${input}\" -r > \"${basecall_bam}\"" \
        "${log_file}"
      exit 1
    }
  fi

  if [[ "${simplex}" == "TRUE" ]]; then
    # NOTE: Internal function (see longairr_utils.sh) - Keeps all reads with simplex tag dx:0
    process_simplex_duplex "0" "${basecall_bam}" "${simplex_bam}" "${simplex_fastq}" "${simplex_fasta}" "${fasta}" >> "${log_file}" 2>&1 || {
      log_message "ERROR" "longairr basecall" \
        "Generating simplex.bam failed" \
        "${log_file}"
      exit 1
    }
    qc_file="simplex.fastq"
  fi

  if [[ "${duplex}" == "TRUE" ]]; then
    # NOTE: Internal function (see longairr_utils.sh) - Keeps all reads with duplex tag dx:1  
    process_simplex_duplex "1" "${basecall_bam}" "${duplex_bam}" "${duplex_fastq}" "${duplex_fasta}" "${fasta}" >> "${log_file}" 2>&1 || {
      log_message "ERROR" "longairr basecall" \
        "Generating duplex.bam failed" \
        "${log_file}"
      exit 1
    }
    qc_file="duplex.fastq"
  fi

  # Combine fastq (fasta) from simplex + duplex reads
  if [[ "${simplex}" == "TRUE" && "${duplex}" == "TRUE" ]]; then
    
    cat "${simplex_fastq}" "${duplex_fastq}" >> "${combined_fastq}"

    if [[ "${fasta}" == "TRUE" ]]; then
      cat "${simplex_fasta}" "${duplex_fasta}" >> "${combined_fasta}"

      rm "${simplex_fasta}"
    fi
    rm "${simplex_bam}" "${simplex_fastq}"
    qc_file="simplex_duplex.fastq"
  fi

  qc_input="${basecall_dir}/${qc_file}"
  log_message "INFO" "longairr basecall" \
    "Choosing \"${qc_file}\" to generate the raw QC-report." \
    "${log_file}"

  # Generate QC report
  # NOTE: Find the reference for third-party software 'NanoPlot' in '/vignette/software_references.md`
  NanoPlot --fastq "${qc_input}" --outdir "${nanoplot_output_dir}" >> "${log_file}" 2>&1 || {
    log_message "ERROR" "longairr basecall" \
      "QC report generation failed while executing: NanoPlot --fastq \"${qc_input}\" --outdir \"${nanoplot_output_dir}\"" \
      "${log_file}"
    exit 1
  }

  # Info messages
  if [[ "${verbose}" == "TRUE" ]]; then
    log_message "INFO" "longairr basecall" \
      "Output directory: \"${nanoplot_output_dir}\"" \
      "${log_file}"
  fi
}


