          --finished-at "${metadata_finished_at}"

          --parameter "library=${library}"
          --parameter "window_length=${window_length}"
          --parameter "anchor_error=${max_error}"
          --parameter "group_field=${group_field}"
          --parameter "min_length=${min_length}"
          --parameter "max_length=${max_length}"
          --parameter "adaptive_filter=${adaptive_filter,,}"
          --parameter "min_group_size=${min_group_size}"
          --parameter "bin_size=${bin_size}"
          --parameter "peak_margin=${peak_margin}"
          --parameter "consensus_min_count=${n_cons}"
          --parameter "consensus_max_gap=${cons_gap}"
          --parameter "consensus_max_error=${cons_error}"
          --parameter "max_reads_per_group=${umi_group_n}"
          --parameter "groups_per_chunk=${umi_per_chunk}"
          --parameter "seed=${seed}"
          --parameter "parallel_jobs=${parallel_cjobs}"

          --count "input_reads=${metadata_input_reads}"
          --count "annotated_reads=${metadata_annotated_reads}"
          --count "length_filtered_reads=${metadata_length_filtered_reads}"
          --count "retained_group_reads=${metadata_retained_reads}"
          --count "consensus_sequences=${metadata_consensus_sequences}"

          --file "input_anchor=${input_anchor}"
          --file "input_sequences=${input_seqs}"
          --file "annotated_sequences=${trim_out}"
          --file "length_filtered_sequences=${trim_trimmed}"
          --file "retained_group_sequences=${subsampled_trimmed}"
          --file "consensus_fasta=${transformed_out}"
          --file "log=${log_file}"
        )

        # Append only parameters and files relevant to the selected library.
        if [[ "${library}" == "visium" ]]; then
          metadata_command+=(
            --parameter "umi_length=${umi_length}"
            --parameter "spbc_length=${spbc_length}"
            --parameter "spbc_error=${spbc_error}"
            --file "visium_spatial_barcodes=${spbc_file}"
          )

        elif [[ "${library}" == "visiumhd" ]]; then
          metadata_command+=(
            --parameter "hd_umi_base_length=${hd_umi_base_length}"
            --parameter "hd_offsets=${hd_offsets}"
            --parameter "hd_spbc_lengths=${hd_spbc_lengths}"
            --parameter "visiumhd_spbc_source=sqlite_index"
            --file "visiumhd_spatial_barcode_index=${longairr_whitelist_index}"
          )

        elif [[ "${library}" == "bulk" ]]; then
          metadata_command+=(
            --parameter "demux=${demux,,}"
            --parameter "umi_length=${umi_length}"
          )
        fi

        # Spatial collapse always writes failed barcode/UMI annotations.
        if [[ "${library}" == "visium" || "${library}" == "visiumhd" ]]; then
          if [[ -f "${spbc_failed_out}" ]]; then
            metadata_command+=(
              --file "failed_spatial_barcodes=${spbc_failed_out}"
            )
          fi
        fi

        if [[ -f "${failed_filtered}" ]]; then
          metadata_command+=(
            --file "failed_adaptive_filter=${failed_filtered}"
          )
        fi

        "${metadata_command[@]}" >> "${log_file}" 2>&1 || {
          log_message "WARNING" "longairr collapse" \
            "Collapse completed, but writing structured metadata failed." \
            "${log_file}"
        }
      fi
    else
      log_message "WARNING" "longairr collapse" \
        "Collapse completed, but the LongAIRR run root could not be initialized." \
        "${log_file}"
    fi
  else
    log_message "WARNING" "longairr collapse" \
      "Collapse completed, but metadata sequence counts could not be computed." \
      "${log_file}"
  fi
  update_progress ${current_step} ${umi_steps}

  #--------VERBOSE--------#

  if [[ "${verbose}" == "TRUE" ]]; then
    log_message "INFO" "longairr collapse" \
      "Output directory: ${collapse_out}" \
      "${log_file}"
  fi
}


